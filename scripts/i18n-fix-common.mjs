const maps = { "zh-CN": zhCN, "zh-TW": zhTW, ja, ko, ru, de, es, fr, hi, ar };

// ── Main ──

const langs = ["zh-CN", "zh-TW", "ja", "ko", "ru", "de", "es", "fr", "hi", "ar"];
const report = JSON.parse(readFileSync("scripts/.i18n-untranslated-report.json", "utf-8"));

for (const lang of langs) {
  const map = maps[lang];
  if (!map) {
    console.log(`${lang}: no translation map, skipping`);
    continue;
  }

  const data = JSON.parse(readFileSync(`src/i18n/locales/${lang}.json`, "utf-8"));
  let applied = 0;

  for (const [key, translated] of Object.entries(map)) {
    setValueByPath(data, key, translated);
    applied++;
  }

  writeFileSync(`src/i18n/locales/${lang}.json`, JSON.stringify(data, null, 2) + "\n", "utf-8");
  console.log(`${lang}: ${applied} translations applied`);
}

console.log("\nDone. Run `node scripts/i18n-detect-untranslated.mjs` to verify.");
