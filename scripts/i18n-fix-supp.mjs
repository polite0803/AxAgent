const maps = {
  "zh-CN": zhCN,
  "zh-TW": { ...zhCN, ...zhTW },
  ja: jaExtra,
  ko: koExtra,
  ru: ruExtra,
  de: deExtra,
  es: esExtra,
  fr: frExtra,
  hi: hiExtra,
  ar: arExtra,
};

for (const lang of ["zh-CN", "zh-TW", "ja", "ko", "ru", "de", "es", "fr", "hi", "ar"]) {
  const map = maps[lang];
  if (!map || Object.keys(map).length === 0) {
    console.log(`${lang}: empty, skipping`);
    continue;
  }
  const data = JSON.parse(readFileSync(`src/i18n/locales/${lang}.json`, "utf-8"));
  let applied = 0;
  for (const [key, translated] of Object.entries(map)) {
    if (translated === null) { continue; }
    setValueByPath(data, key, translated);
    applied++;
  }
  writeFileSync(`src/i18n/locales/${lang}.json`, JSON.stringify(data, null, 2) + "\n", "utf-8");
  console.log(`${lang}: ${applied} applied`);
}
console.log("\nDone.");
