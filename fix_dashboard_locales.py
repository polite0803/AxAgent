def main() -> None:
    for loc_file, trans in TRANSLATIONS.items():
        path = os.path.join(BASE, loc_file)
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)

        # Ensure appHeader section exists
        if "appHeader" not in data:
            data["appHeader"] = {}
        data["appHeader"].update(trans.get("appHeader", {}))

        # Write dashboard section
        data["dashboard"] = trans["dashboard"]

        with open(path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            f.write("\n")

        print(f"  OK {loc_file}  ({len(trans['dashboard'])} dashboard keys)")

    print("Done!")


if __name__ == "__main__":
    main()
